#!/usr/bin/env python3
"""Writes Sources/LucideIcons.swift from an unpacked lucide-static package:
   python3 scripts/gen-lucide.py <package folder>
Only the icons listed here are bundled. Each becomes SVG path data on Lucide's 24×24 grid (drawn by Sources/Icons.swift)."""
import os, re, sys

GROUPS = [
    ("进度", "Progress", "circle-dashed circle-dot loader-circle hourglass circle-pause circle-check check-check circle-x circle-alert ban clock alarm-clock calendar calendar-check flag milestone list-todo kanban"),
    ("产出", "Output", "file-text file-code file-spreadsheet file-archive globe presentation image video film audio-lines mic code-xml terminal braces sheet table chart-column chart-pie network workflow book-open newspaper pen-tool palette"),
    ("工作", "Work", "briefcase building landmark school graduation-cap users user handshake megaphone mail phone message-circle receipt wallet dollar-sign scale gavel shopping-cart truck package"),
    ("技术", "Tech", "cpu server database cloud bot brain atom git-branch bug wrench hammer settings shield lock key link layers puzzle box wand-sparkles"),
    ("生活", "Life", "house heart sun coffee utensils music headphones gamepad-2 camera plane car ship map compass mountain tree-pine leaf sprout dog baby dumbbell stethoscope gift"),
    ("符号", "Symbols", "star sparkles zap flame lightbulb target rocket trophy medal crown gem tag bookmark pin paperclip search microscope telescope eye smile circle square triangle diamond hexagon shapes"),
]
EXTRA = "upload plus chevron-right chevron-down"      # the app's own buttons

def num(x): return float(x)
def fmt(x):
    s = ("%.3f" % x).rstrip("0").rstrip(".")
    return s or "0"

def to_path(tag, a):
    if tag == "path": return a["d"]
    if tag == "line": return f'M{a["x1"]} {a["y1"]}L{a["x2"]} {a["y2"]}'
    if tag in ("polyline", "polygon"):
        p = re.findall(r"-?[\d.]+", a["points"])
        d = "M" + "L".join(f"{p[i]} {p[i+1]}" for i in range(0, len(p), 2))
        return d + ("Z" if tag == "polygon" else "")
    if tag in ("circle", "ellipse"):
        cx, cy = num(a["cx"]), num(a["cy"])
        rx = num(a.get("rx", a.get("r"))); ry = num(a.get("ry", a.get("r")))
        return f"M{fmt(cx-rx)} {fmt(cy)}A{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(cx+rx)} {fmt(cy)}A{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(cx-rx)} {fmt(cy)}Z"
    if tag == "rect":
        x, y, w, h = num(a.get("x", "0")), num(a.get("y", "0")), num(a["width"]), num(a["height"])
        r = num(a.get("rx", a.get("ry", "0")))
        if r == 0: return f"M{fmt(x)} {fmt(y)}H{fmt(x+w)}V{fmt(y+h)}H{fmt(x)}Z"
        return (f"M{fmt(x+r)} {fmt(y)}H{fmt(x+w-r)}A{fmt(r)} {fmt(r)} 0 0 1 {fmt(x+w)} {fmt(y+r)}V{fmt(y+h-r)}"
                f"A{fmt(r)} {fmt(r)} 0 0 1 {fmt(x+w-r)} {fmt(y+h)}H{fmt(x+r)}A{fmt(r)} {fmt(r)} 0 0 1 {fmt(x)} {fmt(y+h-r)}"
                f"V{fmt(y+r)}A{fmt(r)} {fmt(r)} 0 0 1 {fmt(x+r)} {fmt(y)}Z")
    raise SystemExit(f"unknown element {tag}")

def icon(root, name):
    p = os.path.join(root, "icons", name + ".svg")
    if not os.path.exists(p): raise SystemExit(f"no such icon: {name}")
    s = open(p).read()
    out = []
    for m in re.finditer(r"<(path|line|polyline|polygon|circle|ellipse|rect)\b([^>]*?)/?>", s):
        attrs = dict(re.findall(r'([\w-]+)="([^"]*)"', m.group(2)))
        out.append(to_path(m.group(1), attrs))
    return "|".join(out)        # each element starts afresh (a path's first "m" counts from the origin)

root = sys.argv[1]
ver = re.search(r"lucide-static v([\d.]+)", open(os.path.join(root, "icons/circle.svg")).read()).group(1)
names = []
for _, _, n in GROUPS: names += n.split()
names += [n for n in EXTRA.split() if n not in names]
if len(set(names)) != len(names): raise SystemExit("duplicate: " + str([n for n in names if names.count(n) > 1]))
lines = [f"// Generated by scripts/gen-lucide.py: icons from Lucide {ver} (https://lucide.dev).",
         "// ISC License, Copyright (c) 2026 Lucide Icons and Contributors; full notice in Resources/LICENSE-lucide.txt.",
         "", "enum LucideData {", "    /// The picker's groups: (Chinese, English, icon names).",
         "    static let groups: [(zh: String, en: String, names: [String])] = ["]
for zh, en, n in GROUPS:
    lines.append(f'        ("{zh}", "{en}", [' + ", ".join(f'"{x}"' for x in n.split()) + "]),")
lines += ["    ]", "", "    /// Each icon's SVG path data on a 24×24 grid.", "    static let paths: [String: String] = ["]
for n in names: lines.append(f'        "{n}": "{icon(root, n)}",')
lines += ["    ]", "}", ""]
open("Sources/LucideIcons.swift", "w").write("\n".join(lines))
print(len(names), "icons, Lucide", ver)
